import { existsSync, readFileSync, writeFileSync } from "node:fs";
import type { RunRecord } from "./reporter.js";

export interface TestStats {
  title: string;
  file: string;
  runs: number;
  passed: number;
  failed: number;
  flaky: boolean;
  topError?: string;
}

export function loadHistory(path: string): RunRecord[] {
  if (!existsSync(path)) return [];
  return readFileSync(path, "utf8")
    .split("\n")
    .filter(Boolean)
    .map((l) => JSON.parse(l) as RunRecord);
}

export function summarize(records: RunRecord[]): TestStats[] {
  const byTest = new Map<string, { recs: RunRecord[]; errors: Map<string, number> }>();
  for (const r of records) {
    const key = `${r.file} :: ${r.title}`;
    const fresh: { recs: RunRecord[]; errors: Map<string, number> } = { recs: [], errors: new Map() };
    const slot = byTest.get(key) ?? fresh;
    slot.recs.push(r);
    if (r.error) {
      const firstLine = r.error.split("\n")[0].slice(0, 140);
      slot.errors.set(firstLine, (slot.errors.get(firstLine) ?? 0) + 1);
    }
    byTest.set(key, slot);
  }
  return [...byTest.values()]
    .map(({ recs, errors }) => {
      const passed = recs.filter((r) => r.status === "passed").length;
      const failed = recs.filter((r) => r.status === "failed" || r.status === "timedOut").length;
      const topError = [...errors.entries()].sort((a, b) => b[1] - a[1])[0]?.[0];
      return {
        title: recs[0].title,
        file: recs[0].file,
        runs: recs.length,
        passed,
        failed,
        flaky: passed > 0 && failed > 0,
        ...(topError ? { topError } : {}),
      } satisfies TestStats;
    })
    .sort((a, b) => b.failed - a.failed);
}

/** Plain-language root-cause guess for the most common Playwright failure shapes. */
export function diagnose(errorFirstLine: string): string {
  const e = errorFirstLine.toLowerCase();
  if (e.includes("locator") || e.includes("waiting for") || e.includes("strict mode"))
    return "Locator problem — the element moved, was renamed, or the selector now matches differently. Run the healer on this test.";
  if (e.includes("timeout")) return "Timeout — page or element was slower than the test allows; check for a real performance regression before raising the timeout.";
  if (e.includes("expect")) return "Assertion failure — the app behaviour or test data changed; verify which side is correct.";
  if (e.includes("net::") || e.includes("err_")) return "Network/environment failure — likely infrastructure, not the test itself.";
  return "Unclassified — open the trace for this run to see the failing step.";
}

export function renderReport(stats: TestStats[], totalRuns: number): string {
  const flaky = stats.filter((s) => s.flaky);
  const failing = stats.filter((s) => s.failed > 0 && !s.flaky);
  const lines: string[] = [
    "# Healwright — Suite Health Report",
    "",
    `Total recorded test results: ${totalRuns} across ${stats.length} tests.`,
    "",
    "## Flaky tests (passed AND failed across runs — fix these first)",
    "",
  ];
  if (!flaky.length) lines.push("_None detected._", "");
  for (const s of flaky) {
    lines.push(`- **${s.title}** — ${s.passed} passed / ${s.failed} failed of ${s.runs} runs`);
    if (s.topError) lines.push(`  - Most common error: \`${s.topError}\``);
    if (s.topError) lines.push(`  - Likely cause: ${diagnose(s.topError)}`);
  }
  lines.push("", "## Consistently failing tests", "");
  if (!failing.length) lines.push("_None._", "");
  for (const s of failing) {
    lines.push(`- **${s.title}** — failed ${s.failed}/${s.runs} runs`);
    if (s.topError) lines.push(`  - Error: \`${s.topError}\``);
    if (s.topError) lines.push(`  - Likely cause: ${diagnose(s.topError)}`);
  }
  lines.push("", "_Generated by Healwright from .healwright/history.jsonl_");
  return lines.join("\n") + "\n";
}

export function analyzeToFile(historyPath: string, outPath: string): string {
  const records = loadHistory(historyPath);
  const report = renderReport(summarize(records), records.length);
  writeFileSync(outPath, report);
  return report;
}
