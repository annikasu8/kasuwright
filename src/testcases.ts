/**
 * Stage 3 — Manual test case design.
 * Generates structured test cases from each requirement: a positive flow
 * built from the acceptance criteria, plus negative and boundary cases.
 * Steps use a small semantic vocabulary (navigate / enter / click / verify)
 * so Stage 7 can compile the same cases into Playwright code mechanically.
 */
import type { Requirement } from "./brd.js";

export interface TestStep {
  do: "navigate" | "enter" | "click" | "verify" | "call" | "query";
  target: string;
  value?: string;
  expected?: string;
}

export interface TestCase {
  id: string;
  reqId: string;
  title: string;
  type: "positive" | "negative" | "boundary";
  priority: "High" | "Medium" | "Low";
  preconditions: string[];
  steps: TestStep[];
}

interface FlowTemplate { match: RegExp; steps: (r: Requirement) => TestStep[] }

const FLOWS: FlowTemplate[] = [
  {
    match: /log ?in|sign ?in|auth/i,
    steps: () => [
      { do: "navigate", target: "/login" },
      { do: "enter", target: "Email", value: "${validUser.email}" },
      { do: "enter", target: "Password", value: "${validUser.password}" },
      { do: "click", target: "Sign in" },
      { do: "verify", target: "dashboard", expected: "User lands on the dashboard, logged in" },
    ],
  },
  {
    match: /pay|checkout|billing|card/i,
    steps: () => [
      { do: "navigate", target: "/checkout" },
      { do: "enter", target: "Card number", value: "${validCard.number}" },
      { do: "enter", target: "Expiry", value: "${validCard.expiry}" },
      { do: "enter", target: "CVV", value: "${validCard.cvv}" },
      { do: "click", target: "Pay" },
      { do: "verify", target: "confirmation", expected: "Payment succeeds and a confirmation is shown" },
    ],
  },
  {
    match: /search|find|filter/i,
    steps: () => [
      { do: "navigate", target: "/search" },
      { do: "enter", target: "Search", value: "${searchTerm}" },
      { do: "click", target: "Search" },
      { do: "verify", target: "results", expected: "Matching results are listed" },
    ],
  },
  {
    match: /regist|sign ?up|create account/i,
    steps: () => [
      { do: "navigate", target: "/register" },
      { do: "enter", target: "Name", value: "${newUser.name}" },
      { do: "enter", target: "Email", value: "${newUser.email}" },
      { do: "enter", target: "Password", value: "${newUser.password}" },
      { do: "click", target: "Create account" },
      { do: "verify", target: "welcome", expected: "Account is created and a welcome state is shown" },
    ],
  },
];

function positiveSteps(r: Requirement): TestStep[] {
  const flow = FLOWS.find((f) => f.match.test(`${r.title} ${r.description}`));
  const steps: TestStep[] = flow ? flow.steps(r) : [{ do: "navigate", target: "/" }];
  if (r.acceptanceCriteria.length) {
    for (const c of r.acceptanceCriteria) steps.push({ do: "verify", target: "acceptance criteria", expected: c });
  } else if (!flow) {
    steps.push({ do: "verify", target: "outcome", expected: `Requirement met: ${r.title}` });
  }
  return steps;
}

export function generateTestCases(reqs: Requirement[]): TestCase[] {
  const cases: TestCase[] = [];
  for (const r of reqs) {
    const base = `TC-${r.id}`;
    cases.push({
      id: `${base}-01`,
      reqId: r.id,
      title: `${r.title} — happy path`,
      type: "positive",
      priority: "High",
      preconditions: ["Application is deployed and reachable", "Valid test data set is loaded (Stage 4)"],
      steps: positiveSteps(r),
    });
    cases.push({
      id: `${base}-02`,
      reqId: r.id,
      title: `${r.title} — invalid / empty input is rejected`,
      type: "negative",
      priority: "Medium",
      preconditions: ["Application is deployed and reachable"],
      steps: [
        ...positiveSteps(r).filter((s) => s.do !== "verify").map((s) =>
          s.do === "enter" ? { ...s, value: "${invalidData}" } : s),
        { do: "verify", target: "validation", expected: "A clear validation error is shown and no data is saved" },
      ],
    });
    cases.push({
      id: `${base}-03`,
      reqId: r.id,
      title: `${r.title} — boundary values behave correctly`,
      type: "boundary",
      priority: "Medium",
      preconditions: ["Application is deployed and reachable", "Boundary data set is loaded (Stage 4)"],
      steps: [
        ...positiveSteps(r).filter((s) => s.do !== "verify").map((s) =>
          s.do === "enter" ? { ...s, value: "${boundaryData}" } : s),
        { do: "verify", target: "outcome", expected: "Boundary input is handled without errors or data corruption" },
      ],
    });
  }
  return cases;
}

export function testCasesToMarkdown(cases: TestCase[]): string {
  const lines = ["# Manual Test Cases (generated by Kasuwright — review before automation)", ""];
  for (const c of cases) {
    lines.push(`## ${c.id} — ${c.title}`, "", `Type: ${c.type} · Priority: ${c.priority} · Requirement: ${c.reqId}`, "", "**Preconditions**", ...c.preconditions.map((p) => `- ${p}`), "", "**Steps**");
    c.steps.forEach((s, i) => {
      lines.push(`${i + 1}. ${s.do.toUpperCase()} ${s.target}${s.value ? ` = ${s.value}` : ""}${s.expected ? ` → expect: ${s.expected}` : ""}`);
    });
    lines.push("");
  }
  return lines.join("\n");
}
