/**
 * Scheduled Jenkins CI/CD pack (v0.9) — when the user opts in, a run also
 * emits a ready-to-import Jenkins setup under jenkins/:
 *   - Jenkinsfile        — pipeline with a cron trigger, so the suite
 *                          re-runs itself on the chosen schedule
 *   - job-config.xml     — the same pipeline as an importable Jenkins job
 *   - README-jenkins.md  — 5-minute setup instructions
 */

export const SCHEDULES = {
  nightly: { label: "Nightly (around 2 AM)", cron: "H 2 * * *" },
  weekdays: { label: "Weekday mornings (around 8 AM, Mon–Fri)", cron: "H 8 * * 1-5" },
  every6h: { label: "Every 6 hours", cron: "H */6 * * *" },
  weekly: { label: "Weekly (Monday, around 3 AM)", cron: "H 3 * * 1" },
} as const;

export type ScheduleKey = keyof typeof SCHEDULES;

export function isScheduleKey(v: string): v is ScheduleKey {
  return Object.prototype.hasOwnProperty.call(SCHEDULES, v);
}

export interface JenkinsPackOptions {
  schedule: ScheduleKey;
  projectKey: string;
  reportEmail: string;
  appUrl?: string;
  ticketKey?: string;
}

function pipelineCommand(o: JenkinsPackOptions): string {
  const base = o.ticketKey
    ? `npx kasuwright pipeline --jira-ticket ${o.ticketKey} --out runs/latest`
    : "npx kasuwright pipeline --brd docs/BRD.md --out runs/latest";
  return o.appUrl ? `${base} --url ${o.appUrl}` : base;
}

export function scheduledJenkinsfile(o: JenkinsPackOptions): string {
  const s = SCHEDULES[o.schedule];
  return `// Kasuwright scheduled pipeline — ${s.label}
// Generated by Kasuwright. The cron trigger below makes Jenkins re-run the
// whole chain (pipeline -> automation -> evidence -> report) on schedule.
pipeline {
  agent any
  triggers {
    cron('${s.cron}')
  }
  parameters {
    string(name: 'APP_URL', defaultValue: '${o.appUrl ?? ""}', description: 'Application under test (evidence runs)')
  }
  environment {
    REPORT_EMAIL_TO = '${o.reportEmail}'
    PROJECT_KEY = '${o.projectKey}'
  }
  stages {
    stage('Checkout') { steps { checkout scm } }
    stage('Install') { steps { sh 'npm ci' } }
    stage('Kasuwright pipeline') {
      steps { sh '${pipelineCommand(o)}' }
    }
    stage('Automation tests') {
      steps {
        dir('runs/latest/framework') {
          sh 'npm install && npx playwright install --with-deps chromium'
          sh 'npm test'
        }
      }
    }
    stage('Reports') {
      steps {
        archiveArtifacts artifacts: 'runs/latest/report.html, runs/latest/evidence.xlsx, runs/latest/traceability.md', allowEmptyArchive: true, fingerprint: true
        publishHTML(target: [reportName: 'Kasuwright Report', reportDir: 'runs/latest', reportFiles: 'report.html', allowMissing: true])
      }
    }
  }
  post {
    failure {
      mail to: '${o.reportEmail}',
           subject: "Kasuwright scheduled run FAILED — \${env.JOB_NAME} #\${env.BUILD_NUMBER}",
           body: "The scheduled Kasuwright run failed. Report (when generated): runs/latest/report.html\\nBuild: \${env.BUILD_URL}"
    }
    success {
      mail to: '${o.reportEmail}',
           subject: "Kasuwright scheduled run passed — \${env.JOB_NAME} #\${env.BUILD_NUMBER}",
           body: "Scheduled Kasuwright run completed. The HTML report and Excel evidence are archived with the build: \${env.BUILD_URL}"
    }
  }
}
`;
}

function xmlEscape(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/** A complete Jenkins job definition (workflow-job) with the pipeline script embedded — import it and the job is ready. */
export function jenkinsJobConfigXml(o: JenkinsPackOptions): string {
  const s = SCHEDULES[o.schedule];
  return `<?xml version='1.1' encoding='UTF-8'?>
<flow-definition plugin="workflow-job">
  <description>Kasuwright scheduled run — ${xmlEscape(s.label)}. Generated by Kasuwright; edit the schedule in the job configuration.</description>
  <keepDependencies>false</keepDependencies>
  <properties>
    <hudson.model.ParametersDefinitionProperty>
      <parameterDefinitions>
        <hudson.model.StringParameterDefinition>
          <name>APP_URL</name>
          <description>Application under test (evidence runs)</description>
          <defaultValue>${xmlEscape(o.appUrl ?? "")}</defaultValue>
          <trim>false</trim>
        </hudson.model.StringParameterDefinition>
      </parameterDefinitions>
    </hudson.model.ParametersDefinitionProperty>
  </properties>
  <definition class="org.jenkinsci.plugins.workflow.cps.CpsFlowDefinition" plugin="workflow-cps">
    <script>${xmlEscape(scheduledJenkinsfile(o))}</script>
    <sandbox>false</sandbox>
  </definition>
  <triggers>
    <hudson.triggers.TimerTrigger>
      <spec>${s.cron}</spec>
    </hudson.triggers.TimerTrigger>
  </triggers>
  <disabled>false</disabled>
</flow-definition>
`;
}

export function jenkinsSetupReadme(o: JenkinsPackOptions): string {
  const s = SCHEDULES[o.schedule];
  return `# Jenkins setup — Kasuwright scheduled runs

Schedule: **${s.label}** (cron \`${s.cron}\` — Jenkins spreads the exact
minute with the \`H\` hash, so every job does not fire at the same time).

## Option A — import the ready job (fastest)

With the Jenkins CLI:

\`\`\`bash
java -jar jenkins-cli.jar -s http://your-jenkins:8080/ create-job kasuwright-scheduled < job-config.xml
\`\`\`

The job arrives with the pipeline script and the schedule already set.
Open it once and press **Build Now** to verify, then let the schedule
take over.

## Option B — create the job by hand

1. Jenkins → **New Item** → name it (e.g. \`kasuwright-scheduled\`) → **Pipeline** → OK.
2. In the job configuration, tick **Build periodically** and paste the
   schedule: \`${s.cron}\`
3. Under **Pipeline → Definition**, choose *Pipeline script* and paste the
   contents of the \`Jenkinsfile\` in this folder.
4. Save, then **Build Now** once to verify.

## What each scheduled run does

1. Runs the Kasuwright pipeline (${o.ticketKey ? `starting from ticket ${o.ticketKey}` : "from docs/BRD.md"}) into \`runs/latest\`.
2. Installs and runs the generated Playwright framework.
3. Archives \`report.html\` and \`evidence.xlsx\` (step screenshots) on the build.
4. Emails ${o.reportEmail} on success and on failure.

## Changing the schedule later

Edit the cron line in the job configuration (or in the Jenkinsfile's
\`triggers { cron('...') }\` block). Presets Kasuwright offers:
nightly \`H 2 * * *\`, weekday mornings \`H 8 * * 1-5\`, every 6 hours
\`H */6 * * *\`, weekly \`H 3 * * 1\`.

## Notes

- The Jenkins agent needs Node.js 18+ and network access to your Jira
  (for ticket runs) — set JIRA_BASE_URL / JIRA_EMAIL / JIRA_API_TOKEN as
  job credentials or environment variables.
- \`publishHTML\` needs the *HTML Publisher* plugin; without it the report
  is still archived as a build artifact.
`;
}
