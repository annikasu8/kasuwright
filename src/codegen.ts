/**
 * Stages 6+7 — Automation framework creation + scenario compilation.
 * Scaffolds a ready-to-run Playwright framework (config wired to the
 * Healwright reporter, test-data files, DB validation SQL) and compiles the
 * Stage-3 manual cases into Playwright specs. Generated locators are a
 * starting point — when the UI drifts, the Stage-8 healer repairs them.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { TestCase, TestStep } from "./testcases.js";

function valueExpr(v: string): string {
  const m = v.match(/^\$\{(.+)\}$/);
  if (m) return `data.${m[1]}`;
  return JSON.stringify(v);
}

export function stepToCode(s: TestStep): string {
  switch (s.do) {
    case "navigate":
      return `await page.goto(${JSON.stringify(s.target.startsWith("/") || s.target.startsWith("http") ? s.target : "/")});`;
    case "enter":
      return `await page.getByLabel(${JSON.stringify(s.target)}).fill(${valueExpr(s.value ?? "")});`;
    case "click":
      return `await page.getByRole('button', { name: ${JSON.stringify(s.target)} }).click();`;
    case "verify":
      return `// verify: ${s.expected ?? s.target}\n    await expect(page.locator('body')).toContainText(${JSON.stringify((s.expected ?? s.target).slice(0, 60))});`;
    case "call":
      return `// API step (executed by the API runner, see api/): ${s.target}`;
    case "query":
      return `// DB validation (see db/validations.sql): ${s.target}`;
    default:
      return `// step: ${s.do} ${s.target}`;
  }
}

export function testCaseToSpec(cases: TestCase[], reqTitle: string): string {
  const body = cases
    .map((c) => {
      const steps = c.steps.map((s) => `    ${stepToCode(s)}`).join("\n");
      return `  test('${c.id} — ${c.title.replace(/'/g, "\\'")}', async ({ page }) => {\n${steps}\n  });`;
    })
    .join("\n\n");
  return `import { test, expect } from '@playwright/test';
import data from '../data/test-data.json' with { type: 'json' };

// Generated by Healwright from manual test cases — review, then let the
// healer keep locators alive as the UI changes.
test.describe('${reqTitle.replace(/'/g, "\\'")}', () => {
${body}
});
`;
}

export interface ScaffoldResult { files: string[] }

export function scaffoldFramework(
  outDir: string,
  casesByReq: Map<string, { title: string; cases: TestCase[] }>,
  testDataJson: unknown,
  validationsSql: string,
): ScaffoldResult {
  const files: string[] = [];
  const put = (rel: string, content: string) => {
    const p = join(outDir, rel);
    mkdirSync(join(p, ".."), { recursive: true });
    writeFileSync(p, content);
    files.push(rel);
  };

  put("package.json", JSON.stringify({
    name: "healwright-generated-framework",
    private: true,
    scripts: { test: "playwright test", report: "playwright show-report" },
    devDependencies: { "@playwright/test": "^1.48.0" },
  }, null, 2) + "\n");

  put("playwright.config.ts", `import { defineConfig } from '@playwright/test';

export default defineConfig({
  testDir: './tests',
  timeout: 30_000,
  use: { baseURL: process.env.BASE_URL ?? 'http://localhost:3000', trace: 'retain-on-failure', screenshot: 'only-on-failure' },
  reporter: [['list'], ['html', { open: 'never' }]],
});
`);

  put("data/test-data.json", JSON.stringify(testDataJson, null, 2) + "\n");
  put("db/validations.sql", validationsSql);

  for (const [reqId, group] of casesByReq) {
    put(`tests/${reqId.toLowerCase()}.spec.ts`, testCaseToSpec(group.cases, group.title));
  }

  put("README.md", `# Generated Playwright Framework

Created by Healwright from a BRD. Layout:

- \`tests/\` — one spec per requirement, compiled from the approved manual cases
- \`data/test-data.json\` — synthetic test data (valid / invalid / boundary rows)
- \`db/validations.sql\` — database validation queries for the DB-testing stage

Run: \`npm install && npx playwright install && BASE_URL=<app url> npm test\`
`);
  return { files };
}
